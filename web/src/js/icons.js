export const ICON_NAMES = Object.keys(ICON_ART);

export function iconBits(name) {
  const layers = ICON_ART[name];
  if (!layers) throw new Error(`모르는 아이콘 ${name}`);
  const fill = new Uint8Array(256);
  const line = new Uint8Array(256);
  for (const art of layers) {
    const on = (x, y) => x >= 0 && y >= 0 && x < 16 && y < 16 && art[y][x] === "#";
    for (let y = 0; y < 16; y++)
      for (let x = 0; x < 16; x++) {
        if (on(x, y) || !(on(x - 1, y) || on(x + 1, y) || on(x, y - 1) || on(x, y + 1))) continue;
        line[y * 16 + x] = 1;
        fill[y * 16 + x] = 0;
      }
    for (let y = 0; y < 16; y++)
      for (let x = 0; x < 16; x++) {
        if (!on(x, y)) continue;
        fill[y * 16 + x] = 1;
        line[y * 16 + x] = 0;
      }
  }
  let x0 = 16;
  let y0 = 16;
  let x1 = -1;
  let y1 = -1;
  for (let i = 0; i < 256; i++) {
    if (!fill[i] && !line[i]) continue;
    const x = i % 16;
    const y = (i - x) / 16;
    x0 = Math.min(x0, x);
    x1 = Math.max(x1, x);
    y0 = Math.min(y0, y);
    y1 = Math.max(y1, y);
  }
  const dx = Math.floor((16 - (x1 - x0 + 1)) / 2) - x0;
  const dy = Math.floor((16 - (y1 - y0 + 1)) / 2) - y0;
  const move = (bits) => {
    const out = new Uint8Array(256);
    for (let i = 0; i < 256; i++) if (bits[i]) out[(Math.floor(i / 16) + dy) * 16 + (i % 16) + dx] = 1;
    return out;
  };
  return { fill: move(fill), line: move(line) };
}

function pathOf(bits) {
  let d = "";
  for (let y = 0; y < 16; y++) {
    let x = 0;
    while (x < 16) {
      if (!bits[y * 16 + x]) {
        x++;
        continue;
      }
      const start = x;
      while (x < 16 && bits[y * 16 + x]) x++;
      d += `M${start} ${y}h${x - start}v1h${start - x}z`;
    }
  }
  return d;
}

const maskUrl = (bits) => `url("data:image/svg+xml,${encodeURIComponent(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges"><path d="${pathOf(bits)}"/></svg>`)}")`;

export function iconStyle() {
  return ICON_NAMES.map((name) => {
    const { fill, line } = iconBits(name);
    return `.icon[data-icon="${name}"]{--ic-fill:${maskUrl(fill)};--ic-line:${maskUrl(line)}}`;
  }).join("\n");
}
